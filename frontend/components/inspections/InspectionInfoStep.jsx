'use client';

import { FormField, FormSection } from './FormField';
import { toDateInputValue } from '../../lib/inspectionForm';

export default function InspectionInfoStep({ inspectionNumber, inspectionDate, formData, errors, onDateChange, readOnly }) {
  return (
    <FormSection
      number="1"
      title="Inspection Information"
      description="Reference details generated by the Kenya Veterinary Board."
    >
      <div className="inspection-form-grid">
        <FormField id="inspectionNumber" label="Inspection No." hint="Generated by the server when the draft is saved.">
          <input
            id="inspectionNumber"
            type="text"
            value={inspectionNumber || 'Generated on save'}
            readOnly
            aria-readonly="true"
            aria-describedby="inspectionNumber-hint"
          />
        </FormField>

        <FormField id="formNumber" label="Form Number" hint="Optional. Leave blank if not applicable.">
          <input
            id="formNumber"
            type="text"
            value={formData.inspectionDetails.formNumber}
            onChange={(event) => onDateChange('formNumber', event.target.value)}
            disabled={readOnly}
            maxLength={50}
          />
        </FormField>

        <FormField id="inspectionDate" label="Inspection Date" required error={errors.inspectionDate}>
          <input
            id="inspectionDate"
            type="date"
            value={toDateInputValue(inspectionDate)}
            onChange={(event) => onDateChange('date', event.target.value)}
            disabled={readOnly}
            required
            aria-invalid={Boolean(errors.inspectionDate)}
            aria-describedby={errors.inspectionDate ? 'inspectionDate-error' : undefined}
          />
        </FormField>
      </div>
    </FormSection>
  );
}
